def add_sum_to_plot(values):
    total = np.sum(values)

    plt.text(
        0.99, 0.95,
        f'Сумма = {total:.3f}%',
        transform=plt.gca().transAxes,
        ha='right',
        va='top',
        fontsize=12,
        bbox=dict(
            boxstyle='round',
            facecolor='white',
            edgecolor='gray',
            alpha=0.8
        )
    )

    return total
